// Low-latency Offline Motivational Dialogues Engine
// Egypt Arabic dialect supporting Student Profile details
export function getOfflineAIResponse(userMessage: string, profile: any): string {
  const msg = userMessage.trim().toLowerCase();
  const name = profile?.name || 'يا بطل';
  const college = profile?.dreamCollege || 'الكلية اللي بتتمناها';
  const branchText = profile?.branch === 'science' ? 'الأحياء والعلوم' : profile?.branch === 'math' ? 'الرياضيات والمسائل' : 'المواد الأدبية';

  // Define keyword groupings for local parsing
  const isAnxious = msg.includes('خايف') || msg.includes('خوف') || msg.includes('قلق') || msg.includes('توتر') || msg.includes('مرعوب');
  const isLazy = msg.includes('مكسل') || msg.includes('تعبان') || msg.includes('ملل') || msg.includes('زهقت') || msg.includes('مش قادرذاكر') || msg.includes('مش قادر') || msg.includes('احباط') || msg.includes('مكتئب') || msg.includes('قرف');
  const isDream = msg.includes('حلم') || msg.includes('طب') || msg.includes('هندسة') || msg.includes('مجموع') || msg.includes('نتيجة') || msg.includes('كلية');
  const isLost = msg.includes('ضايع') || msg.includes('تراكم') || msg.includes('تراكمات') || msg.includes('ورايا') || msg.includes('نسيت') || msg.includes('مش فاكر') || msg.includes('منهج');
  const isGreeting = msg.includes('أهلاً') || msg.includes('اهلا') || msg.includes('سلام') || msg.includes('ازيك') || msg.includes('مرحبا') || msg.includes('هاي') || msg.includes('مساء') || msg.includes('صباح');
  const isThanks = msg.includes('شكرا') || msg.includes('شكراً') || msg.includes('حبيبي') || msg.includes('تسلم') || msg.includes('شكرا جزيلا');

  if (isAnxious) {
    const responses = [
      `يا ${name}، طبيعي جداً تحس بـ خوف وقلق! الخوف ده معناه إن حلمك غالي عليك ونفسك تفرح أهلك وتدخل ${college}. بس اسمعني.. الخوف عمره ما بيحل المشكلة، الخوف بيبني جبال وهمية. خد نفس عمييق كدة 🧘، واطرد الأفكار السلبية دي. ركز بس في الـ 25 دقيقة الجاية في بومودورو واحد، وانسى الامتحان والنتيجة تماماً دلوقتي. خطوة بخطوة هتوصل! 💖⚡`,
      `خد نفس عميق واسترخي يا ${name}... القلق ده مجرد طاقة زيادة جواك وممكن نوجهها للمذاكرة والتركيز! افتكر دايماً إن ربنا مش بيضيع تعب حد بيسعى، واجه خوفك بإنك تفتح أول صفحة وتذاكر سطر واحد. مفيش مادة تقدر تقف قدام إصرارك! 💪✨`
    ];
    return responses[Math.floor(Math.random() * responses.length)];
  }

  if (isLazy || flagWord(msg, ['مليت', 'زهقان', 'اكتئاب', 'كسل'])) {
    const responses = [
      `يا واد يا وحش! الكسل ده هو الفخ اللي ممكن يضيع تعب أيام! قوم كدة اغسل وشك بماء بارد 💧، واعمل كوباية شاي أو قهوة، وغير مكان المذاكرة. افتكر فرحتك وفرحة والدتك ووالدك يوم النتيجة وبكاء الفرحة الحقيقي.. اللحظة دي تستاهل تدوس على كسلك دلوقتي علشانها! يلا ابدأ بومودورو دراسي سريع في 15 دقيقة بس وسخن دماغك! 🚀🔥`,
      `طبيعي تزهق يا ${name}، إحنا بشر مش آلات، والضغط النفسي بيولد ملل. بس البطل الحقيقي هو اللي بيكمل حتى وهو مش طايق! فكر في التخلص من المهام دي كمعركة ذكاء.. خلص مهامك علشان تستمتع بالبريك بضمير مرتاح. يلا يا بطل ${college} بتناديك! 🎓🦁`
    ];
    return responses[Math.floor(Math.random() * responses.length)];
  }

  if (isLost || flagWord(msg, ['تراكمت', 'متأخر', 'الضياع', 'مش فاهم'])) {
    const responses = [
      `اسمعني كويس يا ${name}.. مفيش حاجة اسمها ضعت ومفيش وقت! لسه في إيديك تصنع المعجزة وتلم المتراكم عليك. قسم المادة الكبيرة لأجزاء صغيرة جداً، وخدها وحدة وحدة. ركز في المواد الحيوية الخاصة بشعبتك و${branchText}.. لما تشيل المتراكم عن عقلك، النفسية هترتاح. ابدأ بمهمة واحدة بسيطة تخلصها واعلم عليها علامة صح! 🎯📚`,
      `التراكمات وهم بنصنعه بنفسنا لما نبص للمنهج كله ككتلة واحدة عملاقة! فكك الكتلة دي لمهام بومودورو صغيرة جداً في جدولك اليومي. كل صفحة بتخلصها هي نصر عظيم وهي حجر أساس لقصر أحلامك في ${college}. ابدأ من دلوقتي بصفحة واحدة بس وبلاش تسويف! ⏱️📖`
    ];
    return responses[Math.floor(Math.random() * responses.length)];
  }

  if (isDream) {
    return `يا عيني على الحلم الجميل! دخول ${college} بمجموع عالي هو أحسن حاجة ممكن تهديها لنفسك ولأهلك السنين دي كلها. اللحظة دي بتتصنع من الدقائق وساعات التعب اللي بتعافر فيها دلوقتي يا ${name}. المذاكرة أحياناً بتبقى تقيلة بس نتيجتها حلوة وطعم النجاح ملوش مثيل. كمل سعي بكل قوتك، وأنا واثق إنك قدها! 🎓✨👑`;
  }

  if (isGreeting) {
    return `أهلاً بك يا بطل الثانوية! إيه الأخبر معاك ومع المذاكرة النهاردة؟ حاسس بيا وأنا معاك في ضهرك دايماً؟ فضفض لي لو مضغوط، أو اضبط المؤقت وابدأ دير وقتك بامتياز.. أنا جمبك! 🤝🌸`;
  }

  if (isThanks) {
    return `لا شكر على واجب يا بطل دراستي! أنا سعيد جداً إني جمبك وبساعدك تعدي السنة دي لبر الأمان وتوصل لـ ${college}. يلا بقى ورينا همتك في المهمة الجاية عشان نملى الحصالة طاقات نجاح! 💪♥️`;
  }

  // Large custom set of supportive responses to keep conversational variety (anti-repetitiveness)
  const generalPool = [
    `يا ${name}، كل محاولة منك بتثبت إنك مقاتل بجد. الثانوية العامة مش سنة دكاترة ومهندسين بس، دي سنة صبر وبناء شخصية حديدية! حتى لو ذاكرت نص ساعة بتركيز أحسن بكتير من 4 ساعات تشتت. كمل بعزيمتك! 💎`,
    `بص حواليك يا بطل.. المذاكرة دي هي تذكرتك الذهبية عشان تغير مستقبلك وتوصل لـ ${college}. ربنا حاطط فيك القدرة على الفهم والصبر.. استعن بالله، وابعد الموبايل وافتح كتابك بابتسامة وهدوء، وكل مسألة هتحلها هتقربك للقمة! 🚀🎓`,
    `أنا فخور جداً بيك وبسعيك المستمر ومقاومتك للتعب والخوف. النهاردة غيمة وتعدي، وبكرة شمس فرحتك بالمجموع تطلع وتنور بيوتكم كلها. خودلك شرب كوباية ماء دافية واستعد للمهمة الجاية يا وحش! 🦁💖`,
    `يا صديقي، مفيش مستحيل طالما بتجرب وتغلط وتتعلم. ${branchText} دي لعبتك الصغيرة لو فهمت الفكرة وحليت عليها بتركيز تام. فخور بمجهودك المستمر ومستنيك تكمل حصتك ببطولة وإنجاز! 👑💫`,
    `ماتسمحش لأي كلمة سلبية أو إحباط من حد يهد طموحك. حلمك في ${college} يخصك أنت لوحدك وهتقدر توصله بإصرارك وعرقك الجميل ده. يلا ارجع للمذاكرة بقلب حديد ونشاط متجدد! 💪🔥`
  ];

  return generalPool[Math.floor(Math.random() * generalPool.length)];
}

// Helper to look for multiple keywords
function flagWord(text: string, words: string[]): boolean {
  return words.some(w => text.includes(w));
}

